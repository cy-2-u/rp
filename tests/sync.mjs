import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { JSDOM } = require('jsdom');
const idb = require('fake-indexeddb');
const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>', { url: 'https://test.local/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
for (const name of ['IDBFactory', 'IDBDatabase', 'IDBObjectStore', 'IDBCursor', 'IDBTransaction', 'IDBKeyRange']) w[name] = idb[name];
Object.assign(w, { indexedDB: new idb.IDBFactory(), TextEncoder, TextDecoder, CompressionStream, DecompressionStream, Blob, structuredClone, fetch: async () => Response.json({ ok: true, authenticated: true }) });
Object.defineProperty(w, 'crypto', { value: globalThis.crypto });
for (const file of ['core.js', 'client.js', 'sync.js']) w.eval(await readFile(new URL('../page/' + file, import.meta.url), 'utf8'));
const P = w.RPClient;
const db = await P.open('RPHubDB', target => target.createObjectStore('store'), 1);
let tx = db.transaction('store', 'readwrite');
const count = Number(process.env.RP_RECORDS || 20);
const started = performance.now();
for (let i = 0; i < count; i++) tx.objectStore('store').put({ text: 'record-' + i }, 'key-' + i);
await P.txDone(tx);
const first = await w.RPSync.prepare(true);
assert.equal(first.entryCount, count + 3);
assert.ok(first.packs.length <= 67);
const preparedMs = performance.now() - started;
const second = await w.RPSync.prepare();
assert.equal(JSON.stringify(second.packs), JSON.stringify(first.packs));
tx = db.transaction('store', 'readwrite'); tx.objectStore('store').put({ text: 'changed' }, 'key-3'); await P.txDone(tx);
const third = await w.RPSync.prepare();
const old = new Set(first.packs.map(p => p.checksum));
assert.equal(third.packs.filter(p => !old.has(p.checksum)).length, 1);
const cacheDb = await P.open('RPHubSyncNext');
for (const pack of third.packs) {
    const rtx = cacheDb.transaction('packs', 'readonly'), request = rtx.objectStore('packs').get(pack.checksum);
    const bytes = await P.txDone(rtx, () => request.result);
    assert.equal(await w.RPCore.hash(bytes), pack.checksum);
}
const long = Array.from({ length: 2000 }, (_, index) => ({ index, content: 'message '.repeat(100) }));
tx = db.transaction('store', 'readwrite'); tx.objectStore('store').put(long, 'long-chat'); await P.txDone(tx);
const longFirst = await w.RPSync.prepare();
long.push({ index: 2000, content: 'appended' });
tx = db.transaction('store', 'readwrite'); tx.objectStore('store').put(long, 'long-chat'); await P.txDone(tx);
const longNext = await w.RPSync.prepare();
const longKnown = new Set(longFirst.packs.map(p => p.checksum));
assert.equal(longNext.packs.filter(p => !longKnown.has(p.checksum)).length, 1, 'append changes only the final pack');
cacheDb.close(); db.close(); dom.window.close();
console.log(JSON.stringify({ test: 'sync', count, packs: first.packs.length, preparedWallMs: Math.round(preparedMs), result: 'full preparation, stability, single-bucket delta and cached checksums passed' }));
