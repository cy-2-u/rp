import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { JSDOM } = require('jsdom'), idb = require('fake-indexeddb');
const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>', { url: 'https://test.local/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
for (const name of ['IDBFactory', 'IDBDatabase', 'IDBObjectStore', 'IDBCursor', 'IDBTransaction', 'IDBKeyRange']) w[name] = idb[name];
Object.assign(w, { indexedDB: new idb.IDBFactory(), TextEncoder, TextDecoder, CompressionStream, DecompressionStream, Blob, structuredClone, fetch: async () => Response.json({ ok: true, authenticated: true }) });
Object.defineProperty(w, 'crypto', { value: globalThis.crypto });
w.document.addEventListener('DOMContentLoaded', e => e.stopImmediatePropagation(), { once: true });
for (const file of ['core.js', 'client.js', 'sync.js']) w.eval(await readFile(new URL('../page/' + file, import.meta.url), 'utf8'));
const P = w.RPClient, C = w.RPCore;
const db = await P.open('RPHubDB', target => target.createObjectStore('store'), 1);
const mib = Number(process.env.RP_MIB || 300), count = mib * 4;
for (let index = 0; index < count; index++) {
    const tx = db.transaction('store', 'readwrite');
    tx.objectStore('store').put(randomBytes(192 * 1024).toString('base64'), 'record-' + index);
    await P.txDone(tx);
}
let compressions = 0;
const original = w.CompressionStream;
w.CompressionStream = class extends original { constructor(...args) { super(...args); compressions++; } };
const baseline = process.memoryUsage().rss;
let peak = baseline;
const timer = setInterval(() => { peak = Math.max(peak, process.memoryUsage().rss); }, 20);
const start = performance.now();
const first = await w.RPSync.prepare(true);
const fullMs = performance.now() - start, fullCompressions = compressions;
compressions = 0;
const repeatStart = performance.now();
const repeat = await w.RPSync.prepare();
const repeatMs = performance.now() - repeatStart;
assert.equal(JSON.stringify(repeat.packs), JSON.stringify(first.packs));
assert.equal(compressions, 0, 'unchanged preparation does not recompress');
const tx = db.transaction('store', 'readwrite'); tx.objectStore('store').put('changed', 'record-0'); await P.txDone(tx);
const deltaStart = performance.now();
const delta = await w.RPSync.prepare();
const deltaMs = performance.now() - deltaStart;
const old = new Set(first.packs.map(p => p.checksum));
const changed = delta.packs.filter(p => !old.has(p.checksum));
assert.ok(changed.length <= Math.ceil(count / 64 / 15) + 1);
assert.ok(first.packs.length < C.LIMIT.packs);
clearInterval(timer); db.close(); w.close();
console.log(JSON.stringify({ test: 'scale', rawMiB: mib, records: count, packs: first.packs.length, compressedMiB: +(first.totalBytes / 1024 ** 2).toFixed(2), fullWallMs: Math.round(fullMs), fullCompressions, unchangedWallMs: Math.round(repeatMs), unchangedCompressions: 0, deltaWallMs: Math.round(deltaMs), deltaCompressions: compressions, deltaPacks: changed.length, processBaselineMiB: Math.round(baseline / 1024 ** 2), processPeakMiB: Math.round(peak / 1024 ** 2), note: 'Process RSS includes fake IndexedDB, Node and its in-memory cache; not browser heap or Cloudflare CPU.' }));
